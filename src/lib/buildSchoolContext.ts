export interface ProjectionHashInputs {
  profile: SchoolProfile
  positions: StaffingPosition[]
  projections: BudgetProjection[]
  gradeExpansionPlan?: GradeExpansionEntry[] | null
}

/**
 * Canonical, stable serialization of every input that affects
 * `computeMultiYearDetailed` / `computeFPFScorecard`. Nested objects are
 * serialized with sorted keys so logically-identical input always yields an
 * identical string. Extending this function is how you tell the advisory and
 * scenario-staleness caches "this changed — invalidate."
 */
function canonicalizeProjectionInputs(input: ProjectionHashInputs): string {
  const { profile, positions, projections, gradeExpansionPlan } = input
  const fa = getAssumptions(profile.financial_assumptions)
  const faKeys = Object.keys(DEFAULT_ASSUMPTIONS).sort() as (keyof FinancialAssumptions)[]
  const faSlice: Record<string, unknown> = {}
  for (const k of faKeys) {
    const v = fa[k]
    faSlice[k] = typeof v === 'number' ? Math.round(v * 10000) / 10000 : v
  }

  const posSlice = positions
    .map(p => ({
      y: p.year,
      t: p.title ?? '',
      pt: p.position_type ?? '',
      c: p.category,
      cls: p.classification ?? '',
      d: p.driver ?? '',
      spp: p.students_per_position ?? 0,
      fte: Math.round((p.fte ?? 0) * 1000) / 1000,
      sal: Math.round(p.annual_salary ?? 0),
    }))
    .sort((a, b) =>
      a.y - b.y
      || a.pt.localeCompare(b.pt)
      || a.t.localeCompare(b.t)
      || a.cls.localeCompare(b.cls)
    )

  // P-UX-16: shape normalization lives in the shared canonicalizeBudgetProjections (sibling of
  // canonicalizeStartupFunding/canonicalizePreOpening*, distinct BudgetProjection shape). It drops
  // null/non-object entries and coerces category/subcategory -> string, amount -> finite, so the
  // projection below sorts + selects on clean data: no localeCompare throw on null cat/sub, no
  // Math.round(NaN) masked into the hash. Byte-identical for canonical input (canonicalization is a
  // no-op), so the slice and the resulting advisory hash are unchanged for existing cached rows.
  const projSlice = canonicalizeBudgetProjections(projections)
    .map(r => ({
      y: r.year,
      cat: r.category,
      sub: r.subcategory,
      rev: r.is_revenue ? 1 : 0,
      amt: Math.round(r.amount ?? 0),
    }))
    .sort((a, b) =>
      a.y - b.y
      || (a.rev - b.rev)
      || a.cat.localeCompare(b.cat)
      || a.sub.localeCompare(b.sub)
    )

  const gepSlice = (gradeExpansionPlan ?? [])
    .map(g => ({
      y: g.year,
      gl: g.grade_level,
      sec: g.sections,
      sps: g.students_per_section,
      n: g.is_new_grade ? 1 : 0,
    }))
    .sort((a, b) => a.y - b.y || a.gl.localeCompare(b.gl))

  // P-UX-18: shape normalization now lives in the shared canonicalizeStartupFunding
  // (one definition for the engine + this hash projection, so the two readers cannot
  // drift). It already drops null/non-object entries and coerces source/amount, so the
  // hash-specific projection below is just sorting + field selection on clean data.
  // Byte-identical for canonical input: canonicalization is a no-op, so the slice and the
  // resulting advisory hash are unchanged for the existing cached rows.
  const fundingSlice = canonicalizeStartupFunding(profile.startup_funding)
    .map(f => ({
      src: f.source,
      amt: Math.round(f.amount),
      t: f.type,
      s: f.status,
      yrs: Array.isArray(f.selectedYears) ? [...f.selectedYears].sort() : null,
      alloc: f.yearAllocations
        ? Object.keys(f.yearAllocations).sort().map(k => [Number(k), Math.round((f.yearAllocations as Record<number, number>)[Number(k)] ?? 0)])
        : null,
    }))
    .sort((a, b) => a.src.localeCompare(b.src))

  const profileSlice = {
    region: profile.region ?? '',
    open_year: profile.planned_open_year,
    grade_config: profile.grade_config ?? '',
    opening_grades: profile.opening_grades ? [...profile.opening_grades].sort() : null,
    buildout_grades: profile.buildout_grades ? [...profile.buildout_grades].sort() : null,
    e1: profile.target_enrollment_y1,
    e2: profile.target_enrollment_y2,
    e3: profile.target_enrollment_y3,
    e4: profile.target_enrollment_y4,
    e5: profile.target_enrollment_y5,
    max_class: profile.max_class_size,
    frl: profile.pct_frl,
    iep: profile.pct_iep,
    ell: profile.pct_ell,
    hicap: profile.pct_hicap,
    retention: profile.retention_rate ?? null,
  }

  return JSON.stringify({
    v: PROMPT_VERSION,
    profile: profileSlice,
    fa: faSlice,
    positions: posSlice,
    projections: projSlice,
    gep: gepSlice,
    funding: fundingSlice,
  })
}

/** djb2 — synchronous, works in Node and the browser, no deps. */
function djb2(str: string): string {
  let h = 5381
  for (let i = 0; i < str.length; i++) {
    h = ((h << 5) + h + str.charCodeAt(i)) | 0
  }
  return (h >>> 0).toString(16).padStart(8, '0')
}

/**
 * Stable hash of every input that drives multi-year projections and advisory
 * output. Used by the advisory cache (`school_profiles.advisory_cache.dataHash`)
 * and by the scenario staleness check (`scenarios.base_data_hash`).
 *
 * Hash shape includes PROMPT_VERSION, ENGINE_VERSION (P-UX-21 engine-code token), and a
 * length discriminator so pre-version caches cleanly miss and old collisions are unreachable.
 * ENGINE_VERSION makes engine-math changes invalidate caches that share inputs + prompt version
 * (closes Divergence #2). Same hash backs scenarios.base_data_hash via the alias below, so the
 * scenario-staleness check is invalidated by engine changes too.
 */
export function computeAdvisoryHash(input: ProjectionHashInputs): string {
  const canonical = canonicalizeProjectionInputs(input)
  return `${PROMPT_VERSION}|${ENGINE_VERSION}|${djb2(canonical)}|${canonical.length}`
}

/** Alias — same function, different name used by scenario staleness. */
export const hashProjectionInputs = computeAdvisoryHash

/**
 * Scenario staleness hash: the projection-input hash over every staffing year and the Year-1
 * projections, exactly as /api/scenarios/calculate stores it in `scenarios.base_data_hash`.
 * The Scenarios tab and the Overview summary compare against it.
 */
export function scenarioBaseHash(input: {
  profile: SchoolProfile
  allPositions: StaffingPosition[]
  projections: BudgetProjection[]
  gradeExpansionPlan?: GradeExpansionEntry[] | null
}): string {
  return hashProjectionInputs({
    profile: input.profile,
    positions: input.allPositions,
    projections: input.projections.filter((p) => p.year === 1),
    gradeExpansionPlan: input.gradeExpansionPlan,
  })
}

const usd = (n: number) => (n < 0 ? `-$${(-n).toLocaleString()}` : `$${n.toLocaleString()}`)

/**
 * The engine rows a context describes: the caller's multiYear (the dashboard's single engine
 * run), or, for a caller without one, a run of the pathway's engine on the same saved data.
 * Every Year-N number in the context comes from these rows, never from a parallel calculation.
 */
function contextRows(
  profile: SchoolProfile,
  positions: StaffingPosition[],
  projections: BudgetProjection[],
  gradeExpansionPlan: GradeExpansionEntry[] | undefined,
  multiYear: MultiYearDetailedRow[] | undefined,
  pathway: string | null | undefined,
): MultiYearDetailedRow[] {
  if (multiYear && multiYear.length > 0) return multiYear
  return runProjections({
    pathway,
    profile,
    positions,
    projections,
    assumptions: getAssumptions(profile.financial_assumptions),
    preOpenCash: computeCarryForward(profile),
    gradeExpansionPlan,
    allPositions: positions,
    startupFunding: profile.startup_funding,
  })
}

/**
 * P-UX-26: a categorical/federal rate the founder set to $0 in Settings is honored by the
 * engine. Say so, so agents do not report the $0 line as missing revenue.
 */
function zeroRateNote(rate: number, studentPct: number): string {
  return rate === 0 && studentPct > 0 ? ' (rate set to $0 in Settings)' : ''
}

const FPF_STATUS_LABEL: Record<HealthStatus, string> = {
  meets: 'MEETS',
  approaching: 'APPROACHES',
  fails: 'DOES NOT MEET',
  na: 'N/A',
}

/**
 * Year 1 month-end cash from computeMonthlyCashFlow (the Cash Flow tab's and Overview chart's
 * model), read against the Year 1 Days-of-Cash band.
 */
export function year1MonthlyCash(y1: MultiYearDetailedRow, pathway?: string | null) {
  const hp = healthPathway(pathway)
  const depreciation = y1.operations.depreciation ?? 0
  const cashFlow = computeMonthlyCashFlow(y1, beginningCashOf(y1), { pathway })
  const points = monthlyCashSeries(cashFlow.months, y1.totalExpenses, depreciation, 1, hp)
  const lines = reserveLines(y1.totalExpenses, depreciation, 1, hp)
  const low = lowestPointIndex(points)
  return {
    cashFlow,
    points,
    lines,
    lowest: low >= 0 ? points[low] : null,
    belowTarget: points.filter((p) => p.status === 'approaching' || p.status === 'fails').map((p) => p.month),
    belowFloor: points.filter((p) => p.status === 'fails').map((p) => p.month),
  }
}

const daysText = (days: number | null) => (days === null ? 'n/a' : `${Math.round(days)} days`)

/** One-paragraph summary of Year 1 month-end cash, for the agent context. */
function monthlyCashSummary(y1: MultiYearDetailedRow, pathway?: string | null): string {
  const m = year1MonthlyCash(y1, pathway)
  if (!m.lowest) return ''
  const target = m.lines[0]
  const floor = m.lines[1]
  const dips = !target
    ? ''
    : m.belowTarget.length === 0
      ? ` Cash stays above the ${target.days}-day target (${usd(Math.round(target.dollars))}) every month.`
      : ` Month-end cash is below the ${target.days}-day target (${usd(Math.round(target.dollars))}) in ${m.belowTarget.join(', ')}${m.belowFloor.length > 0 ? `, and below the ${floor.days}-day floor (${usd(Math.round(floor.dollars))}) in ${m.belowFloor.join(', ')}` : ''}.`
  return `\n\nYEAR 1 MONTHLY CASH (pre-computed): Lowest month-end cash is ${usd(m.lowest.balance)} in ${m.lowest.month} (≈ ${daysText(m.lowest.days)} of cash).${dips}`
}

/** Month-by-month Year 1 cash section, for the full context (briefing and Ask SchoolLaunch). */
function monthlyCashSection(y1: MultiYearDetailedRow, pathway?: string | null): string {
  const m = year1MonthlyCash(y1, pathway)
  if (!m.lowest) return ''
  const { cashFlow } = m
  const target = m.lines[0]
  const floor = m.lines[1]
  const pcts = getStateConfig(pathway).payment_schedule.map((pct, i) => `${MONTHS[i]} ${pct}%`).join(', ')
  const schedule = cashFlow.usesOspiSchedule
    ? `state revenue arrives on the OSPI apportionment schedule (${pcts}), federal grants Oct–Jul, other revenue monthly`
    : `revenue arrives on the payment schedule (${pcts})`
  const monthLines = cashFlow.months.map((mo, i) =>
    `- ${mo.month}: in ${usd(mo.totalInflow)}, out ${usd(mo.payroll + mo.otherExpenses)}, net ${usd(mo.netCashFlow)}, month-end cash ${usd(mo.cumulativeBalance)} (${daysText(m.points[i].days)})`,
  ).join('\n')
  const reserve = target && floor
    ? `\n- Reserve lines: ${target.days}-day target = ${usd(Math.round(target.dollars))}; ${floor.days}-day floor = ${usd(Math.round(floor.dollars))}`
    : ''
  const dips = target
    ? m.belowTarget.length === 0
      ? `\n- Month-end cash stays above the ${target.days}-day target all year.`
      : `\n- Months below the ${target.days}-day target: ${m.belowTarget.join(', ')}${floor ? `; below the ${floor.days}-day floor: ${m.belowFloor.length > 0 ? m.belowFloor.join(', ') : 'none'}` : ''}`
    : ''
  const lowMonths = cashFlow.lowScheduleMonths.length > 0
    ? `\n- Smallest scheduled payments: ${cashFlow.lowScheduleMonths.join(', ')}`
    : ''
  return `

YEAR 1 MONTHLY CASH (pre-computed by the budget engine, as on the Cash Flow tab — September to August; ${schedule}; expenses spread evenly, depreciation excluded):
- Starting cash (Sep 1, carried from pre-opening): ${usd(cashFlow.startingCash)}
${monthLines}
- Lowest month-end cash: ${usd(m.lowest.balance)} in ${m.lowest.month} (≈ ${daysText(m.lowest.days)} of cash)${reserve}${dips}${lowMonths}`
}

/**
 * Summarized context for advisory agents. Contains pre-computed metrics as settled facts
 * and staffing/operations detail, but NOT raw revenue breakdowns or per-year financials
 * that would let the model recompute metrics independently.
 *
 * `pathway` selects the health bands for the Days of Cash verdicts (WA: Commission FPF
 * stages; any other pathway: the generic benchmarks) and drops WA-only lines for generic
 * schools. Omitted, it defaults to WA.
 */
export function buildAgentContextString(
  schoolName: string,
  profile: SchoolProfile,
  positions: StaffingPosition[],
  projections: BudgetProjection[],
  gradeExpansionPlan?: GradeExpansionEntry[],
  multiYear?: MultiYearDetailedRow[],
  scorecard?: FPFScorecard,
  pathway?: string | null,
): string {
  const assumptions = getAssumptions(profile.financial_assumptions)
  const hp = healthPathway(pathway)
  const isWa = hp === 'wa_charter'
  const rows = contextRows(profile, positions, projections, gradeExpansionPlan, multiYear, pathway)
  const y1 = rows[0]
  const rev = y1.revenue
  const ops = y1.operations
  const enroll = y1.enrollment

  const operatingRevenue = rev.operatingRevenue
  const totalRevenue = rev.total
  const totalPersonnel = y1.personnel.total
  const totalOperations = ops.total
  const totalExpenses = y1.totalExpenses
  const netPosition = y1.net
  const personnelPct = personnelPctOfRevenue(y1).toFixed(1)
  const facilityPct = facilityPctOfRevenue(y1).toFixed(1)
  const totalFte = positions.reduce((s, p) => s + p.fte, 0)
  const breakEven = breakEvenEnrollment(y1)
  const teacherCount = positions.filter((p) => p.category === 'certificated' && /teacher/i.test(p.title)).reduce((s, p) => s + p.fte, 0)
  const studentTeacherRatio = teacherCount > 0 ? Math.round(enroll / teacherCount) : 0

  // Days of Cash: the engine's reserveDays (equals the FPF scorecard's Days of Cash), passed
  // to agents pre-computed so they never derive it.
  const daysOfCashValues = rows.map((r) => r.reserveDays)
  const daysOfCashY1 = y1.reserveDays
  const daysY1 = evaluateDaysOfCash(daysOfCashY1, 1, hp)

  // Beginning/ending cash (year-end CASH, including the depreciation add-back)
  const beginningCash = beginningCashOf(y1)
  const endingCash = y1.endingCash

  // Enrollment summary
  const hasExpansion = gradeExpansionPlan && gradeExpansionPlan.length > 0
  const retRate = getRetentionRate(profile)
  let enrollSummary: string
  if (hasExpansion) {
    const expansionEnrollments = computeExpansionEnrollments(gradeExpansionPlan!, retRate)
    enrollSummary = expansionEnrollments.map(e =>
      `Year ${e.year}: ${e.total} students [${e.grades.join(', ')}]${e.newGrades.length > 0 ? ` (adding: ${e.newGrades.join(', ')})` : ''}`
    ).join('; ')
    enrollSummary += ` | Growth model: Multi-year enrollment projection applies ${retRate}% annual retention to continuing-grade students; new-grade-level students enroll at full planned capacity each year. Year 2+ totals reflect retained students plus new-grade-level additions. Once full buildout is reached, total enrollment may decline year-over-year because new-grade additions stop while retention continues to apply.`
  } else {
    enrollSummary = `Y1: ${profile.target_enrollment_y1}, Y2: ${profile.target_enrollment_y2}, Y3: ${profile.target_enrollment_y3}, Y4: ${profile.target_enrollment_y4}, Y5: ${profile.target_enrollment_y5 || profile.target_enrollment_y4}`
  }

  // Staffing list (agents need this for analysis)
  const staffingList = positions.map(p => {
    const cost = p.annual_salary * p.fte
    const total = cost + calcBenefits(cost, assumptions.benefits_load_pct / 100)
    return `- ${p.title}: ${p.fte} FTE, $${p.annual_salary.toLocaleString()} salary, ${p.category} (total with benefits: $${total.toLocaleString()})`
  }).join('\n')

  // Year 1 operations from the engine row, with per-pupil/per-FTE context
  const perStudent = (amt: number) => enroll > 0 ? `$${Math.round(amt / enroll).toLocaleString()}/student` : ''
  const perFte = (amt: number) => totalFte > 0 ? `$${Math.round(amt / totalFte).toLocaleString()}/FTE` : ''
  const depreciation = ops.depreciation ?? 0
  const interest = ops.interest ?? 0
  const facilityLine = depreciation > 0 || interest > 0
    ? `- Facilities: ${usd(ops.facilities)} lease/occupancy + ${usd(depreciation)} depreciation + ${usd(interest)} debt interest = ${usd(facilityCostOf(y1))} (${facilityPct}% of operating revenue)`
    : `- Facilities: ${usd(ops.facilities)} (${facilityPct}% of operating revenue)`
  const opsBreakdown = [
    facilityLine,
    `- Insurance: ${usd(ops.insurance)}`,
    `- Supplies & Materials: ${usd(ops.supplies)} (${perStudent(ops.supplies)})`,
    `- Technology: ${usd(ops.technology)} (${perStudent(ops.technology)})`,
    `- Curriculum & Materials: ${usd(ops.curriculum)} (${perStudent(ops.curriculum)})`,
    `- Professional Development: ${usd(ops.profDev)} (${perFte(ops.profDev)})`,
    `- Food Service: ${ops.foodService > 0 ? `${usd(ops.foodService)} (${perStudent(ops.foodService)})` : 'Not budgeted'}${assumptions.food_service_offered ? ' [program enabled]' : ''}`,
    `- Transportation: ${ops.transportation > 0 ? `${usd(ops.transportation)} (${perStudent(ops.transportation)})` : 'Not budgeted'}${assumptions.transportation_offered ? ' [program enabled]' : ''}`,
    `- Contracted Services: ${usd(ops.contracted)} (${perStudent(ops.contracted)})`,
    `- Marketing & Outreach: ${usd(ops.marketing)} (${perStudent(ops.marketing)})`,
    `- Fundraising: ${usd(ops.fundraising)}`,
    `- Authorizer Fee: ${usd(ops.authorizerFee)}${isWa ? ' (3% of state apportionment)' : ''}`,
    `- Misc/Contingency: ${usd(ops.contingency)} (${totalExpenses > 0 ? (ops.contingency / totalExpenses * 100).toFixed(1) : '0'}% of total expenses)`,
    ...(ops.customExpense ?? []).filter((c) => c.amount !== 0).map((c) => `- ${c.name}: ${usd(c.amount)}`),
  ].join('\n')

  // Days of cash trajectory in prose
  const cashTrajectory = daysOfCashValues.map((d, i) => `Year ${i + 1}: ${d} days`).join(', ')

  // Multi-year trajectory in prose (settled facts, not raw data)
  let multiYearProse = ''
  if (rows.length > 1) {
    const lastYear = rows[rows.length - 1]
    const lastEndingCash = lastYear.endingCash
    const lastDays = lastYear.reserveDays
    multiYearProse = `\n\nFIVE-YEAR TRAJECTORY:\nThe school grows from ${y1.enrollment} students in Year 1 to ${lastYear.enrollment} in Year ${lastYear.year}. Cash reserves ${lastEndingCash > endingCash ? 'strengthen' : 'decline'} over the projection period, reaching ${usd(lastEndingCash)} (${lastDays} days cash) by Year ${lastYear.year}. ${evaluateDaysOfCash(lastDays, lastYear.year, hp).long}`
  }

  // FPF scorecard summary in prose
  let scorecardProse = ''
  if (scorecard) {
    const meetsCounts = scorecard.measures.map(m =>
      `${m.name}: ${FPF_STATUS_LABEL[fromFpfStatus(m.statuses[0])]} Stage 1`
    ).join('; ')
    scorecardProse = `\n\nFPF SCORECARD (Year 1): ${meetsCounts}\nOverall: ${scorecard.overallStatus} — ${scorecard.overallMessage}`
  }

  // Categorical grants for compliance analysis (WA revenue model only)
  const categoricalGrants = isWa
    ? `\n\nCATEGORICAL GRANT REVENUE: Title I: ${usd(rev.titleI)}${profile.pct_frl >= 40 ? ' (Schoolwide eligible)' : ' (Not eligible)'}${zeroRateNote(assumptions.title_i_per_pupil, profile.pct_frl)}, IDEA: ${usd(rev.idea)}${zeroRateNote(assumptions.idea_per_pupil, profile.pct_iep)}, LAP: ${usd(rev.lap)}${zeroRateNote(assumptions.lap_per_pupil, profile.pct_frl)}, LAP High Poverty: ${usd(rev.lapHighPoverty)}${zeroRateNote(assumptions.lap_high_poverty_per_pupil, profile.pct_frl)}, TBIP: ${usd(rev.tbip)}${zeroRateNote(assumptions.tbip_per_pupil, profile.pct_ell)}, HiCap: ${usd(rev.hicap)}${zeroRateNote(assumptions.hicap_per_pupil, profile.pct_hicap)}`
    : ''

  return `SCHOOL: ${schoolName}
Grade configuration: ${profile.grade_config} | Region: ${profile.region} | Opening: ${profile.planned_open_year}
Demographics: ${profile.pct_frl}% FRL, ${profile.pct_iep}% IEP, ${profile.pct_ell}% ELL, ${profile.pct_hicap}% HiCap

ENROLLMENT: ${enrollSummary}

YEAR 1 FINANCIAL SUMMARY:
End of Year 1: ${daysY1.long}
- Beginning Cash: ${usd(beginningCash)} (carried forward from pre-opening)
- Ending Cash: ${usd(endingCash)}
- Days of Cash by year: ${cashTrajectory}
- Total Revenue: ${usd(totalRevenue)} (Operating: ${usd(operatingRevenue)})
- Total Expenses: ${usd(totalExpenses)}
- Net Position: ${usd(netPosition)}
- Personnel % of Operating Revenue: ${personnelPct}%
- Facility % of Operating Revenue: ${facilityPct}%
- Break-Even Enrollment: ${breakEven} students (target: ${enroll})
- Student-to-teacher ratio: ${studentTeacherRatio}:1

STAFFING (Year 1, ${totalFte} FTE, ${usd(totalPersonnel)} total):
${staffingList}

OPERATIONS (Year 1, ${usd(totalOperations)} total):
${opsBreakdown}${categoricalGrants}${monthlyCashSummary(y1, pathway)}${multiYearProse}${scorecardProse}`
}

/**
 * Full context for the briefing synthesis and Ask SchoolLaunch. `pathway` as in
 * buildAgentContextString (defaults to WA).
 */
export function buildSchoolContextString(
  schoolName: string,
  profile: SchoolProfile,
  positions: StaffingPosition[],
  projections: BudgetProjection[],
  gradeExpansionPlan?: GradeExpansionEntry[],
  multiYear?: MultiYearDetailedRow[],
  scorecard?: FPFScorecard,
  pathway?: string | null,
): string {
  const assumptions = getAssumptions(profile.financial_assumptions)
  const isWa = healthPathway(pathway) === 'wa_charter'
  const rows = contextRows(profile, positions, projections, gradeExpansionPlan, multiYear, pathway)
  const y1 = rows[0]
  const rev = y1.revenue
  const ops = y1.operations
  const enroll = y1.enrollment
  const aafte = y1.aafte

  // Operating revenue (recurring; excludes interest and one-time grants on WA) is the
  // denominator for Personnel %, Facility % and break-even, as on the dashboard.
  const operatingRevenue = rev.operatingRevenue
  const totalRevenue = rev.total
  const totalPersonnel = y1.personnel.total
  const totalOperations = ops.total
  const totalFte = positions.reduce((s, p) => s + p.fte, 0)
  const personnelPct = personnelPctOfRevenue(y1).toFixed(1)
  const facilityCost = facilityCostOf(y1)
  const facilityPct = facilityPctOfRevenue(y1).toFixed(1)
  const breakEven = breakEvenEnrollment(y1)

  const teacherCount = positions.filter((p) => p.category === 'certificated' && /teacher/i.test(p.title)).reduce((s, p) => s + p.fte, 0)
  const studentTeacherRatio = teacherCount > 0 ? Math.round(enroll / teacherCount) : 0

  const staffingList = positions.length > 0
    ? positions.map((p) => {
        const baseCost = p.annual_salary * p.fte
        const cost = baseCost + calcBenefits(baseCost, assumptions.benefits_load_pct / 100)
        return `- ${p.title}: ${p.fte} FTE, $${p.annual_salary.toLocaleString()} salary, ${p.category}, total cost with benefits: $${cost.toLocaleString()}`
      }).join('\n')
    : 'No positions entered'

  const opsLines: [string, number][] = [
    ['Facilities', ops.facilities],
    ['Supplies & Materials', ops.supplies],
    ['Contracted Services', ops.contracted],
    ['Technology', ops.technology],
    ['Authorizer Fee', ops.authorizerFee],
    ['Insurance', ops.insurance],
    ['Curriculum & Materials', ops.curriculum],
    ['Professional Development', ops.profDev],
    ['Food Service', ops.foodService],
    ['Transportation', ops.transportation],
    ['Marketing & Outreach', ops.marketing],
    ['Fundraising', ops.fundraising],
    ['Misc/Contingency', ops.contingency],
    ...(ops.customExpense ?? []).filter((c) => c.amount !== 0).map((c): [string, number] => [c.name, c.amount]),
    ...(ops.depreciation ? [['Facility Depreciation (non-cash)', ops.depreciation] as [string, number]] : []),
    ...(ops.interest ? [['Facility Debt Interest', ops.interest] as [string, number]] : []),
  ]
  const opsBreakdown = totalOperations !== 0
    ? opsLines.map(([label, amount]) => `- ${label}: ${usd(amount)}`).join('\n')
    : 'No operations expenses entered'

  const hasExpansion = gradeExpansionPlan && gradeExpansionPlan.length > 0
  const retRate = getRetentionRate(profile)

  let enrollmentSection: string
  if (hasExpansion) {
    const expansionEnrollments = computeExpansionEnrollments(gradeExpansionPlan!, retRate)
    const expansionLines = expansionEnrollments.map((e) => {
      const newGradeStr = e.newGrades.length > 0 ? ` (adding grades: ${e.newGrades.join(', ')})` : ''
      return `- Year ${e.year}: ${e.total} students [grades: ${e.grades.join(', ')}] (returning: ${e.returning}, new grade: ${e.newGrade})${newGradeStr}`
    }).join('\n')
    enrollmentSection = `ENROLLMENT (Grade Expansion Model, ${retRate}% retention):
${expansionLines}
- Growth model: ${retRate}% annual retention applied to continuing-grade students; new-grade-level students enroll at full planned capacity each year. Year 2+ totals reflect retained students plus new-grade-level additions. Once full buildout is reached, total enrollment may decline year-over-year because new-grade additions stop while retention continues to apply.
- Opening grades: ${profile.opening_grades?.join(', ') || 'not set'}
- Buildout grades: ${profile.buildout_grades?.join(', ') || 'not set'}
- Retention rate: ${retRate}%`
  } else {
    const e1 = profile.target_enrollment_y1
    enrollmentSection = `ENROLLMENT:
- Year 1: ${e1} students
- Year 2: ${profile.target_enrollment_y2} students
- Year 3: ${profile.target_enrollment_y3} students
- Year 4: ${profile.target_enrollment_y4} students
- Year 5: ${profile.target_enrollment_y5 || profile.target_enrollment_y4} students
- Growth Y1→Y2: ${e1 > 0 ? (((profile.target_enrollment_y2 - e1) / e1) * 100).toFixed(0) : 0}%
- Growth Y2→Y3: ${profile.target_enrollment_y2 > 0 ? (((profile.target_enrollment_y3 - profile.target_enrollment_y2) / profile.target_enrollment_y2) * 100).toFixed(0) : 0}%`
  }

  const regionFactor = assumptions.regionalization_factor || 1.0
  // Regionalized lines: show the factor so each formula multiplies out to the engine amount.
  const regionalized = regionFactor !== 1.0 ? ` × ${regionFactor} regionalization` : ''
  const optionalLine = (show: boolean, line: string) => (show ? `\n${line}` : '')
  const customRevenueLines = (rev.customRevenue ?? [])
    .filter((c) => c.amount !== 0)
    .map((c) => `\n- ${c.name}: ${usd(c.amount)} (${c.recurring ? 'recurring' : 'one-time'})`)
    .join('')
  const nonOperatingLines =
    optionalLine(rev.interestIncome > 0, `- Interest Income: ${usd(rev.interestIncome)}`)
    + optionalLine(rev.grantRevenue > 0, `- Startup Grants (one-time): ${usd(rev.grantRevenue)}`)

  const revenueSection = isWa
    ? `REVENUE (Year 1, AAFTE: ${aafte} of ${enroll} headcount):
- Regular Ed Apportionment: ${usd(rev.regularEd)} (${aafte} AAFTE × ${usd(assumptions.regular_ed_per_pupil)}${regionalized})
- SPED Apportionment: ${usd(rev.sped)} (${aafte} × ${profile.pct_iep}% IEP × ${usd(assumptions.sped_per_pupil)}${regionalized})
- State Special Education: ${usd(rev.stateSped)} (${Math.round(enroll * profile.pct_iep / 100)} SPED students × ${usd(assumptions.state_sped_per_pupil)}${regionalized})${zeroRateNote(assumptions.state_sped_per_pupil, profile.pct_iep)}
- Facilities Revenue: ${usd(rev.facilitiesRev)}
- Levy Equity: ${usd(rev.levyEquity)} (${aafte} AAFTE × ${usd(assumptions.levy_equity_per_student)})${optionalLine(rev.smallSchoolEnhancement > 0, `- Small School Enhancement: ${usd(rev.smallSchoolEnhancement)}`)}
- Title I: ${usd(rev.titleI)}${profile.pct_frl >= 40 ? ' (Schoolwide eligible)' : ' (Not eligible, FRL < 40%)'}${zeroRateNote(assumptions.title_i_per_pupil, profile.pct_frl)}
- IDEA: ${usd(rev.idea)}${zeroRateNote(assumptions.idea_per_pupil, profile.pct_iep)}
- LAP: ${usd(rev.lap)}${zeroRateNote(assumptions.lap_per_pupil, profile.pct_frl)}
- LAP High Poverty: ${usd(rev.lapHighPoverty)}${zeroRateNote(assumptions.lap_high_poverty_per_pupil, profile.pct_frl)}
- TBIP: ${usd(rev.tbip)}${zeroRateNote(assumptions.tbip_per_pupil, profile.pct_ell)}
- HiCap: ${usd(rev.hicap)}${zeroRateNote(assumptions.hicap_per_pupil, profile.pct_hicap)}${optionalLine(rev.foodServiceRev > 0, `- Food Service (NSLP): ${usd(rev.foodServiceRev)}`)}${optionalLine(rev.transportationRev > 0, `- Transportation (State): ${usd(rev.transportationRev)}`)}${customRevenueLines}
- Operating Revenue (recurring, excludes interest and grants): ${usd(operatingRevenue)}${nonOperatingLines}
- Total Revenue (including interest and one-time grants): ${usd(totalRevenue)}`
    : `REVENUE (Year 1, ${enroll} students):
- Tuition / per-pupil revenue: ${usd(rev.regularEd)}
- Other operating revenue (fees, fundraising, interest): ${usd(operatingRevenue - rev.regularEd)}
- Operating Revenue: ${usd(operatingRevenue)}${optionalLine(rev.grantRevenue > 0, `- Startup Grants (one-time): ${usd(rev.grantRevenue)}`)}
- Total Revenue (including one-time grants): ${usd(totalRevenue)}`

  const regionLine = isWa
    ? `\nRegionalization factor: ${regionFactor}${regionFactor !== 1.0 ? ` (multiplies state per-pupil rates: Regular Ed, SPED, State Special Ed)` : ''}`
    : ''

  return `School: ${schoolName}
Grade configuration: ${profile.grade_config}
Region: ${profile.region}${regionLine}
Planned opening year: ${profile.planned_open_year}
Max class size: ${profile.max_class_size}

${enrollmentSection}

DEMOGRAPHICS:
- Free/Reduced Lunch: ${profile.pct_frl}%
- IEP: ${profile.pct_iep}%
- ELL: ${profile.pct_ell}%
- Highly Capable: ${profile.pct_hicap}%

${revenueSection}

STAFFING (Year 1):
${staffingList}
Total FTE: ${totalFte}, Total Personnel Cost: ${usd(totalPersonnel)}
Student-to-teacher ratio: ${studentTeacherRatio}:1

OPERATIONS (Year 1):
${opsBreakdown}
Total Operations: ${usd(totalOperations)}

KEY METRICS (pre-computed by the budget engine — use these exact numbers, do not independently calculate):
- Net Position: ${usd(y1.net)}
- Days of Cash (Year 1): ${y1.reserveDays} days — USE THIS VALUE, do not calculate independently
- Personnel % of Operating Revenue: ${personnelPct}% (= ${usd(totalPersonnel)} ÷ ${usd(operatingRevenue)})
- Break-Even Enrollment: ${breakEven} students (target: ${enroll})
- Facility % of Operating Revenue: ${facilityPct}% (= ${usd(facilityCost)} facility cost ÷ ${usd(operatingRevenue)})
NOTE: Personnel %, Facility % and Break-Even Enrollment use Operating Revenue as the base (excludes one-time grants); break-even = Year 1 expenses ÷ operating revenue per student. Facility cost is the facilities line plus, when the facility is financed, depreciation and debt interest.${isWa ? ' This matches the Commission FPF evaluation methodology.' : ''}${monthlyCashSection(y1, pathway)}

MULTI-YEAR SUMMARY (Years 1-${rows.length}):
${rows.map((r) =>
    `- Year ${r.year}: Revenue ${usd(r.revenue.total)}, Expenses ${usd(r.totalExpenses)}, Net ${usd(r.net)}, Ending Cash ${usd(r.endingCash)}, ${r.reserveDays} days cash`
  ).join('\n')}${scorecard ? `

FPF SCORECARD (Commission Financial Performance Framework):
${scorecard.measures.map((m) => `- ${m.name}: ${m.values.map((v, i) => `Y${i + 1}=${v === null ? 'N/A' : v}`).join(', ')} | Stage 1: ${m.stage1Target}, Stage 2: ${m.stage2Target} | Status: ${m.statuses.join(', ')}`).join('\n')}
Overall: ${scorecard.overallStatus} — ${scorecard.overallMessage}` : ''}

IMPORTANT: Use ONLY the pre-computed financial metrics provided above. Do not independently calculate, estimate, or infer any financial figures. The KEY METRICS, YEAR 1 MONTHLY CASH, MULTI-YEAR SUMMARY, and FPF SCORECARD sections contain exact values from the budget engine — reference these numbers directly.`
}
